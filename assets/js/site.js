function applyTranslations(language) {
  const dictionary = translations[language] || translations.en;
  document.documentElement.lang = language;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.getAttribute('data-i18n');
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const key = element.getAttribute('data-i18n-html');
    if (dictionary[key]) {
      element.innerHTML = dictionary[key];
    }
  });

  document.querySelectorAll('[data-i18n-ph]').forEach((element) => {
    const key = element.getAttribute('data-i18n-ph');
    if (dictionary[key]) {
      element.setAttribute('placeholder', dictionary[key]);
    }
  });

  const langSelect = document.getElementById('lang-select');
  if (langSelect) {
    langSelect.value = language;
  }

  try {
    localStorage.setItem('neoveo-lang', language);
  } catch (error) {
    console.error(error);
  }
}

function getPreferredLanguage() {
  try {
    const stored = localStorage.getItem('neoveo-lang');
    if (stored && translations[stored]) {
      return stored;
    }
  } catch (error) {
    console.error(error);
  }

  const browserLanguage = navigator.language.slice(0, 2);
  return translations[browserLanguage] ? browserLanguage : 'en';
}

function setupMenu() {
  const toggle = document.querySelector('[data-menu-toggle]');
  const body = document.body;

  if (!toggle) {
    return;
  }

  toggle.addEventListener('click', () => {
    body.classList.toggle('menu-open');
  });

  document.querySelectorAll('.nav-links a, .nav-actions a').forEach((link) => {
    link.addEventListener('click', () => {
      body.classList.remove('menu-open');
    });
  });
}

function setupReveal() {
  const elements = document.querySelectorAll('.reveal');

  if (!('IntersectionObserver' in window) || elements.length === 0) {
    elements.forEach((element) => element.classList.add('is-visible'));
    return;
  }

  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  elements.forEach((element) => observer.observe(element));
}

function setupForm() {
  const form = document.getElementById('lead-form');
  const status = document.getElementById('form-status');

  if (!form || !status) {
    return;
  }

  const updateStatus = (key, isError = false) => {
    const language = document.documentElement.lang || 'en';
    const dictionary = translations[language] || translations.en;
    status.textContent = dictionary[key] || '';
    status.style.color = isError ? '#b42318' : '';
  };

  updateStatus('form.statusReady');

  form.addEventListener('submit', (event) => {
    event.preventDefault();

    const formData = new FormData(form);
    const name = String(formData.get('name') || '').trim();
    const company = String(formData.get('company') || '').trim();
    const email = String(formData.get('email') || '').trim();
    const phone = String(formData.get('phone') || '').trim();
    const vertical = String(formData.get('vertical') || '').trim();
    const challenge = String(formData.get('challenge') || '').trim();

    if (!name || !company || !email || !challenge) {
      updateStatus('form.statusMissing', true);
      return;
    }

    updateStatus('form.statusReady');

    const subject = encodeURIComponent(`Neoveo.ai lead - ${company} - ${vertical || 'General inquiry'}`);
    const body = encodeURIComponent(
      [
        `Name: ${name}`,
        `Company: ${company}`,
        `Email: ${email}`,
        `Phone: ${phone || 'Not provided'}`,
        `Vertical: ${vertical || 'Not selected'}`,
        '',
        'Challenge:',
        challenge
      ].join('\n')
    );

    window.location.href = `mailto:contact@neoveo.ai?subject=${subject}&body=${body}`;
  });
}

function setupLanguageSelector() {
  const langSelect = document.getElementById('lang-select');
  if (!langSelect) {
    return;
  }

  langSelect.addEventListener('change', (event) => {
    applyTranslations(event.target.value);
  });
}

function updateYear() {
  document.querySelectorAll('[data-current-year]').forEach((element) => {
    element.textContent = String(new Date().getFullYear());
  });
}

document.addEventListener('DOMContentLoaded', () => {
  updateYear();
  setupMenu();
  setupLanguageSelector();
  setupReveal();
  setupForm();
  applyTranslations(getPreferredLanguage());
});
